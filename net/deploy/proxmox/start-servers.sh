#!/bin/bash
# net/deploy/proxmox/start-servers.sh — bring up the master + N game instances
# on the local Proxmox-hosted Ubuntu VM (xerox@192.168.0.213, "ubuntu-cynosure").
#
#   ROOT=~/relcs ./start-servers.sh              # master + 5 instances, 32 players each
#   ROOT=~/relcs COUNT=2 ./start-servers.sh      # master + 2 instances
#   ROOT=~/relcs RCON=secret ./start-servers.sh  # admin password for generated configs
#
# Port map (UDP only — there is no TCP game port, rcon rides the game port):
#   7800                       master (server list + favorites)
#   7777 7781 7782 7783 7784   instances 1..5
#   7778                       LAN discovery, instance 1 only (fixed port)
#
# Configs are generated into $ROOT/servers/<n>.cfg the first time an instance is
# started; edit them there afterwards (an existing config is never overwritten).
# Instance 1 keeps the historical hostname and profiles.db, so the player data of
# the long-running "reLCS Proxmox" server survives the update; instances 2..5 get
# their own SQLite database. resources/ is shared (the server only reads packs).
#
# Servers announce to the master through the box's own LAN IP, not loopback: with
# a loopback source the master falls back to the address the server advertises
# (LanIPv4() = first RFC1918 address), which on a host with container bridges can
# be a private bridge address that LAN clients cannot reach.
#
# Processes are started with setsid and a pid file; "already running" is decided
# by process name + executable path, so a stale pid file can never spawn a
# duplicate listener.
set -uo pipefail

ROOT=${ROOT:-$HOME/relcs}
COUNT=${COUNT:-5}
RCON=${RCON:-change-me}
MASTER_PORT=${MASTER_PORT:-7800}
BIND_IP=${BIND_IP:-$(hostname -I | awk '{print $1}')}
PORTS=(7777 7781 7782 7783 7784)
NAMES=("reLCS Proxmox" "reLCS Proxmox #2" "reLCS Proxmox #3" "reLCS Proxmox #4" "reLCS Proxmox #5")

BIN="$ROOT/net/bin"
BIN_SERVER="$BIN/reLCS-server"
BIN_MASTER="$BIN/reLCS-master"

cd "$ROOT" || { echo "!! no $ROOT" >&2; exit 1; }
mkdir -p logs run servers

for exe in "$BIN_SERVER" "$BIN_MASTER"; do
  [ -x "$exe" ] || { echo "!! missing $exe (build with net/build-linux.sh and install it)" >&2; exit 1; }
done
if [ "$COUNT" -gt "${#PORTS[@]}" ]; then
  echo "!! COUNT=$COUNT exceeds the port map (${#PORTS[@]} instances)" >&2
  exit 1
fi

# pid of an already running copy of $1 (absolute path) whose command line
# contains $2, or nothing. All instances share the same executable name, so the
# command line marker is what tells them apart (master: -port N, instance:
# -config <path>).
running_pid() {
  local exe=$1 marker=$2 pid
  for pid in $(pgrep -x "$(basename "$exe")" 2>/dev/null); do
    [ "$(readlink -f "/proc/$pid/exe" 2>/dev/null)" = "$exe" ] || continue
    if [ -n "$marker" ]; then
      tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -qF -- "$marker" || continue
    fi
    echo "$pid"
    return 0
  done
  return 1
}

start_proc() { # start_proc <label> <pidfile> <logfile> <exe> <marker> [args...]
  local label=$1 pf=$2 log=$3 exe=$4 marker=$5; shift 5
  local pid existed
  if existed=$(running_pid "$exe" "$marker"); then
    echo "$existed" > "$pf"
    echo "== $label already running (pid $existed)"
    return 0
  fi
  setsid "$exe" "$@" >> "$log" 2>&1 < /dev/null &
  pid=$!
  echo "$pid" > "$pf"
  sleep 2
  if [ -d "/proc/$pid" ] || existed=$(running_pid "$exe" "$marker"); then
    [ -d "/proc/$pid" ] || { pid=$existed; echo "$pid" > "$pf"; }
    echo "== $label started (pid $pid)"
  else
    echo "!! $label failed to start — last log lines:"
    tail -5 "$log" 2>/dev/null
    return 1
  fi
}

echo "== master (UDP $MASTER_PORT, favorites master.db)"
start_proc "master" run/master.pid logs/master.log "$BIN_MASTER" "-port $MASTER_PORT" \
           -port "$MASTER_PORT" -favorites "$ROOT/master.db" || exit 1

failed=0
for ((i = 0; i < COUNT; i++)); do
  n=$((i + 1))
  port=${PORTS[$i]}
  cfg="$ROOT/servers/$n.cfg"
  if [ ! -f "$cfg" ]; then
    profiles=$([ "$n" = 1 ] && echo "profiles.db" || echo "profiles-$n.db")
    lan=$([ "$n" = 1 ] && echo 1 || echo 0)   # 7778 is a single fixed listener
    cat > "$cfg" <<EOF
# reLCS instance $n — generated by net/deploy/proxmox/start-servers.sh
hostname=${NAMES[$i]}
port=$port
# 2000 = the protocol's player ceiling; a 32 cap here made the LAN fleet
# advertise 0/32 rows that could never be joined at public scale.
maxplayers=2000
gamemode=survivor

announce=1
master=$BIND_IP
master_port=$MASTER_PORT

lan_discover=$lan

# admin rcon rides UDP $port in band — rotate this and keep this file private
rcon_password=$RCON

tick_rate=20
stream_distance=250
profiles=$profiles
resources=resources
vehicles=vehicles.cfg
netstats_interval=0
EOF
    echo "== wrote $cfg"
  fi
  start_proc "${NAMES[$i]} :$port" "run/server-$n.pid" "logs/server-$n.log" \
             "$BIN_SERVER" "-config $cfg" -config "$cfg" || failed=1
done

echo
echo "== listening sockets"
ss -lunp 2>/dev/null | grep -E "reLCS" || true
echo "== master list (3 s)"
sleep 3
tail -3 logs/master.log 2>/dev/null || true
exit $failed
